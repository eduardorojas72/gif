function convertirDesdeCOP(montoCOP, monedaDestino) {
  const tasa = TASAS_COP_POR_MONEDA[monedaDestino] || TASAS_COP_POR_MONEDA.COP;
  return Number(montoCOP || 0) / tasa;
}

